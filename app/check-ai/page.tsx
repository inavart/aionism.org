"use client";

import { useState } from "react";
import { Copy, ChevronDown, ChevronUp } from "lucide-react";
import { CHECK_AI_PROMPT } from "../../content/check-ai-prompt";

export default function CheckAIPage() {
    const [copied, setCopied] = useState(false);
    const [expanded, setExpanded] = useState(false);

    const copyToClipboard = () => {
        navigator.clipboard.writeText(CHECK_AI_PROMPT);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
    };

    const isLong = CHECK_AI_PROMPT.length > 800;
    const previewText = isLong ? CHECK_AI_PROMPT.substring(0, 800) + "..." : CHECK_AI_PROMPT;

    return (
        <div className="max-w-4xl mx-auto py-32 px-6">
            <h1 className="text-5xl md:text-7xl font-serif font-bold mb-8 text-center">How does your AI read this concept?</h1>
            <p className="text-center text-xl opacity-70 mb-16 max-w-2xl mx-auto">
                Copy the prompt, paste it into the assistant you use, and compare its assessment with your own reading.
            </p>

            <div className="space-y-12">
                {/* Step 1 */}
                <div className="bg-[var(--foreground)]/5 p-8 rounded-2xl border border-[var(--foreground)]/10">
                    <h3 className="text-xl font-bold font-mono uppercase mb-4 flex items-center gap-2">
                        <span className="w-8 h-8 rounded-full bg-[var(--foreground)] text-[var(--background)] flex items-center justify-center">1</span>
                        Copy the Prompt
                    </h3>

                    <div className={`bg-[var(--background)] p-4 rounded font-mono text-sm opacity-80 border border-[var(--foreground)]/20 mb-4 relative ${expanded || !isLong ? "max-h-none overflow-auto" : "max-h-96 overflow-hidden"}`}>
                        <pre className="whitespace-pre-wrap break-words">
                            {expanded ? CHECK_AI_PROMPT : previewText}
                        </pre>
                        {isLong && !expanded && (
                            <div className="absolute bottom-0 left-0 right-0 h-20 bg-gradient-to-t from-[var(--background)] to-transparent pointer-events-none"></div>
                        )}
                    </div>

                    {isLong && (
                        <button
                            onClick={() => setExpanded(!expanded)}
                            className="w-full py-2 mb-4 border border-[var(--foreground)]/20 rounded font-mono text-sm flex items-center justify-center gap-2 hover:bg-[var(--foreground)]/5 transition-colors"
                        >
                            {expanded ? <><ChevronUp size={16} /> Collapse</> : <><ChevronDown size={16} /> Expand Full Prompt</>}
                        </button>
                    )}

                    <button
                        onClick={copyToClipboard}
                        className="w-full py-4 bg-[var(--accent-primary)] text-white font-bold uppercase tracking-widest rounded hover:opacity-90 transition-opacity flex items-center justify-center gap-2"
                    >
                        {copied ? "Copied!" : <><Copy size={18} /> Copy Prompt</>}
                    </button>
                </div>

                {/* Step 2 */}
                <div>
                    <h3 className="text-xl font-bold font-mono uppercase mb-4 flex items-center gap-2">
                        <span className="w-8 h-8 rounded-full bg-[var(--foreground)] text-[var(--background)] flex items-center justify-center">2</span>
                        Paste it into an assistant
                    </h3>
                    <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                        <a href="https://chatgpt.com" target="_blank" rel="noopener noreferrer" className="p-6 border border-[var(--foreground)]/20 rounded-xl hover:border-[var(--accent-secondary)] transition-colors text-center font-bold">
                            Open ChatGPT
                        </a>
                        <a href="https://claude.ai" target="_blank" rel="noopener noreferrer" className="p-6 border border-[var(--foreground)]/20 rounded-xl hover:border-[var(--accent-secondary)] transition-colors text-center font-bold">
                            Open Claude
                        </a>
                        <a href="https://gemini.google.com" target="_blank" rel="noopener noreferrer" className="p-6 border border-[var(--foreground)]/20 rounded-xl hover:border-[var(--accent-secondary)] transition-colors text-center font-bold">
                            Open Gemini
                        </a>
                    </div>
                    <p className="mt-6 text-sm opacity-60 text-center">
                        An AI&apos;s answer is an opinion generated by a model, not an endorsement or a verification.
                    </p>
                </div>
            </div>
        </div>
    );
}
